  const LANG_FOLDER_MAP = {
    ES: '',
    CA: 'cat',
    EN: 'en',
    FR: 'fr',
    ZH: 'zh',
    RU: 'ru',
  };

  function detectLangFromContext() {
    const bodyLang = (document.body?.dataset?.lang || '').toUpperCase();
    if (SUPPORTED.includes(bodyLang)) return bodyLang;

    const path = window.location.pathname.toLowerCase();
    if (/\/cat(\/|$)/.test(path)) return 'CA';
    if (/\/en(\/|$)/.test(path)) return 'EN';
    if (/\/fr(\/|$)/.test(path)) return 'FR';
    if (/\/zh(\/|$)/.test(path)) return 'ZH';
    if (/\/ru(\/|$)/.test(path)) return 'RU';

    try {
      const saved = (localStorage.getItem(STORAGE_KEY) || 'ES').toUpperCase();
      if (SUPPORTED.includes(saved)) return saved;
    } catch {}
    return 'ES';
  }

  let currentLang = detectLangFromContext();
  try {
    localStorage.setItem(STORAGE_KEY, currentLang);
  } catch {}

  function t(key) {
    return (DICT[currentLang] && DICT[currentLang][key]) || DICT.ES[key] || key;
  }

  function getPropertyText(prop) {
    if (!prop) return { title: '', description: '' };
    const xmlKey = XML_LANG_MAP[currentLang] || 'es';
    const tr = prop.translations && prop.translations[xmlKey];
    const fallback = (prop.translations && prop.translations.es) || {};
    return {
      title: (tr && tr.title) || prop.title || fallback.title || '',
      description: (tr && tr.description) || prop.description || fallback.description || '',
    };
  }

  function applyDomTranslations(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.dataset.i18n;
      if (key) el.textContent = t(key);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.dataset.i18nPlaceholder;
      if (key) el.setAttribute('placeholder', t(key));
    });
  }

  function setLang(code) {
    const upper = String(code || 'ES').toUpperCase();
    if (!SUPPORTED.includes(upper)) return;
    currentLang = upper;
    try {
      localStorage.setItem(STORAGE_KEY, currentLang);
    } catch {}
    document.documentElement.lang = currentLang.toLowerCase();
    applyDomTranslations(document);
    document.dispatchEvent(new CustomEvent('language:changed', { detail: { lang: currentLang } }));
  }

  window.FincasI18n = {
    getLang: () => currentLang,
    setLang,
    t,
    getPropertyText,
    applyDomTranslations,
    getFolderForLang: (code) => LANG_FOLDER_MAP[String(code || 'ES').toUpperCase()] ?? '',
  };

  document.documentElement.lang = currentLang.toLowerCase();
